"""PROCESS's input-variable declarations, vendored from `process/core/input.py` (§23.2).

`INPUT_VARIABLES` is the table that turns a name in an `IN.DAT` into a field on the
`DataStructure`: the area it lives in, the type it casts to, and whether it addresses an
array. `importer.py` needs exactly that and nothing else, so exactly that is vendored --
**not** the `range`/`choices` bounds, the two `additional_actions` hooks or the
`InputVariable` class itself. Bounds are input *validation*, which is the next layer
(`_audit/init_audit.md` §1: `init.py` alone holds 51 raises), and vendoring an unused
field is a drift surface with no consumer.

Two names carry no field at all -- `ixc` and `icc` set `set_variable=False` and reach
`DataStructure` only through an `additional_actions` hook. They are the problem
statement, not values, so they are recorded here as `module=None` and the importer
routes them accordingly.

Generated by introspection, never hand-typed. To regenerate::

    from process.core.input import INPUT_VARIABLES
    for name, c in INPUT_VARIABLES.items():
        module = repr(c.module) if isinstance(c.module, str) else "None"
        print(f"    {name!r}: InputDecl({module}, {c.type.__name__}"
              f"{', True' if c.array else ''}),")

`tests/functional_process/test_importer.py::TestVendoredTable` asserts the name set and
every field equals PROCESS's, so a drift fails a test instead of silently changing an
answer.
"""

