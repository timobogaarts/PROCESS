def bounds_for(names, declared=None):
    """Fuzz bounds for `names`: the contract's own where it has one, else `DOMAIN`.

    A name in neither is an error rather than a skip -- a silently unfuzzed argument is
    a hole in the sweep, and the fix is one line in `DOMAIN`.

    Raises
    ------
    KeyError
        If a name has no declared bound and no shared domain.
    """
    declared = declared or {}
    out, missing = {}, []
    for name in names:
        if name in declared:
            out[name] = declared[name]
        elif name in DOMAIN:
            out[name] = DOMAIN[name]
        else:
            missing.append(name)
    if missing:
        raise KeyError(
            f"no fuzz domain for {sorted(missing)} -- add them to "
            f"`_harness/fuzz_domain.DOMAIN`, or bound them on the contract"
        )
    return out
